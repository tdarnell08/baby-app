#!/usr/bin/env python3
"""Pre-render the Kid Mode voice clips (bundled, so Kid Mode works offline) and the src/data/kidVoice.ts map."""

from __future__ import annotations

import asyncio
from pathlib import Path

import edge_tts

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "kidvoice"
TS = ROOT / "src" / "data" / "kidVoice.ts"

VOICE = "en-US-JennyNeural"
RATE = "-18%"
PITCH = "+14Hz"

NUMBERS = ["one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]

ANIMALS = {
    "cow": ("Cow", "Moooo!"),
    "dog": ("Dog", "Woof woof!"),
    "cat": ("Cat", "Meow!"),
    "duck": ("Duck", "Quack quack!"),
    "sheep": ("Sheep", "Baaa!"),
    "pig": ("Pig", "Oink oink!"),
    "horse": ("Horse", "Neigh!"),
    "frog": ("Frog", "Ribbit!"),
    "lion": ("Lion", "Roarrr!"),
    "chick": ("Chick", "Peep peep!"),
    "owl": ("Owl", "Hoo hoo!"),
    "bee": ("Bee", "Bzzzz!"),
}

COLORS = ["red", "blue", "yellow", "green", "orange", "purple", "pink"]
SHAPES = ["circle", "square", "triangle", "star", "heart"]

LETTERS = {
    "a": "Ay", "b": "Bee", "c": "Cee", "d": "Dee", "e": "Ee", "f": "Eff", "g": "Gee", "h": "Aitch",
    "i": "Eye", "j": "Jay", "k": "Kay", "l": "El", "m": "Em", "n": "En", "o": "Oh", "p": "Pee",
    "q": "Cue", "r": "Are", "s": "Ess", "t": "Tee", "u": "You", "v": "Vee", "w": "Double you",
    "x": "Ex", "y": "Why", "z": "Zee",
}

PHRASES = {
    "smell": "Smell the flower. Breathe in.",
    "blow": "Blow out the candle. Breathe out.",
    "alldone": "All done. Great job. Let's take one big, slow breath.",
    "peekaboo": "Peekaboo!",
    "found": "You found it!",
    "notthere": "Not here. Try again!",
    "yay": "Yay!",
    "great": "Great job!",
    "pop": "Pop!",
    "tryletter": "Trace the letter with your finger.",
}


def clips() -> dict[str, str]:
    out: dict[str, str] = {}
    for i, name in enumerate(NUMBERS, start=1):
        out[f"n{i}"] = name.capitalize() + "."
    for key, (name, sound) in ANIMALS.items():
        out[f"an-{key}"] = name + "."
        out[f"as-{key}"] = sound
        out[f"aw-{key}"] = f"Where is the {name.lower()}?"
    for c in COLORS:
        out[f"c-{c}"] = c.capitalize() + "."
    for s in SHAPES:
        out[f"sh-{s}"] = s.capitalize() + "."
    for k, v in LETTERS.items():
        out[f"l-{k}"] = v + "."
    for k, v in PHRASES.items():
        out[f"p-{k}"] = v
    return out


async def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    table = clips()
    sem = asyncio.Semaphore(6)

    async def one(key: str, text: str) -> None:
        async with sem:
            await edge_tts.Communicate(text, VOICE, rate=RATE, pitch=PITCH).save(str(OUT / f"{key}.mp3"))

    await asyncio.gather(*(one(k, t) for k, t in table.items()))
    lines = [
        "// Generated by scripts/generate-kid-voices.py. Do not edit by hand.",
        "export const kidVoice = {",
    ]
    for key in table:
        lines.append(f"  '{key}': require('../../assets/kidvoice/{key}.mp3'),")
    lines += ["} as const;", "", "export type KidClip = keyof typeof kidVoice;", ""]
    TS.write_text("\n".join(lines))
    print(f"Wrote {len(table)} clips")


if __name__ == "__main__":
    asyncio.run(main())
